import type { ColumnIR, ForeignKeyIR, IndexIR, MigrationOpLike, SchemaIR, TableIR } from '../../core/ir';
import type { MigrationOp } from '../../migrate/ops';

/** Postgres and CockroachDB share almost all DDL; the flavor picks the differences. */
export type PgFlavor = 'postgres' | 'cockroach';

export const quoteIdent = (name: string): string => `"${name.replace(/"/g, '""')}"`;

export const quoteString = (value: string): string => `'${value.replace(/'/g, "''")}'`;

const actions: Record<string, string> = {
  cascade: 'CASCADE',
  restrict: 'RESTRICT',
  'set null': 'SET NULL',
  'set default': 'SET DEFAULT',
  'no action': 'NO ACTION',
};

/** The enum type name of a column (named enums are per column unless shared on purpose). */
export function enumTypeName(table: string, column: ColumnIR): string {
  return column.enumName ?? `${table}_${column.name}`;
}

/** Native column type for a neutral column, without identity or default. */
export function columnType(flavor: PgFlavor, table: string, column: ColumnIR): string {
  if (column.nativeType) return column.nativeType;
  switch (column.type) {
    case 'string':
      return column.length !== undefined ? `varchar(${column.length})` : 'varchar';
    case 'text':
      return 'text';
    case 'int':
      // CockroachDB reads a bare INT as INT8; ask for 32 bits explicitly.
      return flavor === 'cockroach' ? 'int4' : 'integer';
    case 'bigint':
      return 'bigint';
    case 'float':
      return 'double precision';
    case 'decimal':
      if (column.precision === undefined) return 'numeric';
      return column.scale !== undefined ? `numeric(${column.precision}, ${column.scale})` : `numeric(${column.precision})`;
    case 'boolean':
      return 'boolean';
    case 'datetime':
      return 'timestamptz(3)';
    case 'date':
      return 'date';
    case 'time':
      return 'time';
    case 'json':
      return 'jsonb';
    case 'bytes':
      return 'bytea';
    case 'uuid':
      return 'uuid';
    case 'enum':
      return quoteIdent(enumTypeName(table, column));
  }
}

const isAutoincrement = (column: ColumnIR) => column.default?.kind === 'autoincrement';

/** SQL for a column default, or undefined for none (and for identity columns). */
export function defaultSql(table: string, column: ColumnIR): string | undefined {
  const d = column.default;
  if (!d) return undefined;
  switch (d.kind) {
    case 'autoincrement':
      return undefined;
    case 'now':
      if (column.type === 'date') return 'CURRENT_DATE';
      if (column.type === 'time') return 'LOCALTIME';
      return 'CURRENT_TIMESTAMP';
    case 'random':
      return 'gen_random_uuid()';
    case 'sql':
      return String(d.value);
    case 'value':
      return literal(table, column, d.value);
  }
}

/** A typed SQL literal for a default value (already JSON friendly). */
export function literal(table: string, column: ColumnIR, value: unknown): string {
  if (value === null || value === undefined) return 'NULL';
  switch (column.type) {
    case 'int':
    case 'float':
      return String(Number(value));
    case 'bigint':
      return String(BigInt(value as string | number));
    case 'decimal':
      return /^-?\d+(\.\d+)?$/.test(String(value)) ? String(value) : quoteString(String(value));
    case 'boolean':
      return value ? 'true' : 'false';
    case 'json':
      return `${quoteString(JSON.stringify(value))}::jsonb`;
    case 'bytes': {
      const bytes = Array.isArray(value) ? (value as number[]) : Array.from(value as Uint8Array);
      return `'\\x${bytes.map((b) => b.toString(16).padStart(2, '0')).join('')}'::bytea`;
    }
    case 'datetime':
      return quoteString(value instanceof Date ? value.toISOString() : String(value));
    case 'enum':
      return `${quoteString(String(value))}::${quoteIdent(enumTypeName(table, column))}`;
    default:
      return quoteString(String(value));
  }
}

function columnDefinition(flavor: PgFlavor, table: string, column: ColumnIR): string {
  const parts = [quoteIdent(column.name), columnType(flavor, table, column)];
  if (isAutoincrement(column)) parts.push('GENERATED BY DEFAULT AS IDENTITY');
  const def = defaultSql(table, column);
  if (def !== undefined) parts.push(`DEFAULT ${def}`);
  if (!column.nullable) parts.push('NOT NULL');
  return parts.join(' ');
}

function foreignKeyClause(fk: ForeignKeyIR): string {
  return (
    `CONSTRAINT ${quoteIdent(fk.name)} FOREIGN KEY (${fk.columns.map(quoteIdent).join(', ')}) ` +
    `REFERENCES ${quoteIdent(fk.refTable)} (${fk.refColumns.map(quoteIdent).join(', ')}) ` +
    `ON DELETE ${actions[fk.onDelete] ?? 'NO ACTION'} ON UPDATE ${actions[fk.onUpdate] ?? 'NO ACTION'}`
  );
}

export function createIndexSql(table: string, index: IndexIR): string {
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quoteIdent(index.name)} ON ${quoteIdent(table)} (${index.columns.map(quoteIdent).join(', ')})`;
}

export function createTableSql(flavor: PgFlavor, table: TableIR): string[] {
  const lines = table.columns.map((c) => `  ${columnDefinition(flavor, table.name, c)}`);
  if (table.primaryKey.length > 0) {
    lines.push(`  CONSTRAINT ${quoteIdent(`${table.name}_pkey`)} PRIMARY KEY (${table.primaryKey.map(quoteIdent).join(', ')})`);
  }
  for (const fk of table.foreignKeys) lines.push(`  ${foreignKeyClause(fk)}`);
  if (flavor === 'cockroach') {
    // Inline indexes are created with the table. A separate CREATE INDEX runs a
    // backfill job, which takes seconds even on an empty table.
    for (const i of table.indexes) {
      lines.push(`  ${i.unique ? 'UNIQUE ' : ''}INDEX ${quoteIdent(i.name)} (${i.columns.map(quoteIdent).join(', ')})`);
    }
    return [`CREATE TABLE ${quoteIdent(table.name)} (\n${lines.join(',\n')}\n)`];
  }
  return [`CREATE TABLE ${quoteIdent(table.name)} (\n${lines.join(',\n')}\n)`, ...table.indexes.map((i) => createIndexSql(table.name, i))];
}

function findTable(schema: SchemaIR, name: string): TableIR | undefined {
  return schema.tables.find((t) => t.name === name);
}

function alterColumn(flavor: PgFlavor, op: Extract<MigrationOp, { kind: 'alterColumn' }>): string[] {
  const t = quoteIdent(op.table);
  const c = quoteIdent(op.column);
  const out: string[] = [];
  const alter = (clause: string) => out.push(`ALTER TABLE ${t} ALTER COLUMN ${c} ${clause}`);
  const wasIdentity = isAutoincrement(op.from);
  const isIdentity = isAutoincrement(op.to);
  const fromDefault = defaultSql(op.table, op.from);
  const toDefault = defaultSql(op.table, op.to);

  if (op.changes.type) {
    // A default of the old type may not cast to the new one: drop it first and put the new one back.
    if (fromDefault !== undefined) alter('DROP DEFAULT');
    if (flavor === 'cockroach') out.push('SET enable_experimental_alter_column_type_general = true');
    const type = columnType(flavor, op.table, op.to);
    alter(`TYPE ${type} USING ${usingCast(op.from, op.to, op.column, type)}`);
    if (toDefault !== undefined) alter(`SET DEFAULT ${toDefault}`);
  } else if (op.changes.default && !(wasIdentity || isIdentity)) {
    alter(toDefault === undefined ? 'DROP DEFAULT' : `SET DEFAULT ${toDefault}`);
  }
  if (op.changes.default && wasIdentity !== isIdentity) {
    if (wasIdentity) alter('DROP IDENTITY IF EXISTS');
    else {
      if (fromDefault !== undefined && !op.changes.type) alter('DROP DEFAULT');
      alter('ADD GENERATED BY DEFAULT AS IDENTITY');
    }
    if (wasIdentity && toDefault !== undefined) alter(`SET DEFAULT ${toDefault}`);
  }
  if (op.changes.nullable) alter(op.to.nullable ? 'DROP NOT NULL' : 'SET NOT NULL');
  return out;
}

function usingCast(from: ColumnIR, to: ColumnIR, column: string, type: string): string {
  const c = quoteIdent(column);
  // Enums and json only convert through text.
  if (from.type === 'enum' || to.type === 'enum' || from.type === 'json' || to.type === 'json') return `${c}::text::${type}`;
  if (from.type === 'boolean' && (to.type === 'int' || to.type === 'bigint')) return `${c}::int::${type}`;
  return `${c}::${type}`;
}

/** True when `from` keeps its order inside `to`, so new values can be inserted in place. */
function isSubsequence(from: string[], to: string[]): boolean {
  let i = 0;
  for (const value of to) if (value === from[i]) i++;
  return i === from.length;
}

function alterEnum(flavor: PgFlavor, op: Extract<MigrationOp, { kind: 'alterEnum' }>, schema: SchemaIR): string[] {
  const name = quoteIdent(op.name);
  const kept = op.from.filter((v) => op.to.includes(v));
  if (flavor === 'cockroach' || (op.removed.length === 0 && isSubsequence(kept, op.to))) {
    const out: string[] = [];
    // Insert each new value next to a value that already exists, so the final order matches `to`.
    const present = [...kept];
    for (const value of op.to) {
      if (present.includes(value)) continue;
      const index = op.to.indexOf(value);
      const before = op.to.slice(index + 1).find((v) => present.includes(v));
      const after = op.to.slice(0, index).reverse().find((v) => present.includes(v));
      const position = before !== undefined ? ` BEFORE ${quoteString(before)}` : after !== undefined ? ` AFTER ${quoteString(after)}` : '';
      out.push(`ALTER TYPE ${name} ADD VALUE ${quoteString(value)}${position}`);
      present.push(value);
    }
    if (flavor === 'cockroach') for (const value of op.removed) out.push(`ALTER TYPE ${name} DROP VALUE ${quoteString(value)}`);
    return out;
  }
  // Postgres cannot drop enum values: recreate the type and convert the columns through text.
  const old = quoteIdent(`${op.name}_old`);
  const out = [`ALTER TYPE ${name} RENAME TO ${old}`, `CREATE TYPE ${name} AS ENUM (${op.to.map(quoteString).join(', ')})`];
  for (const ref of op.columns) {
    const column = findTable(schema, ref.table)?.columns.find((c) => c.name === ref.column);
    const t = quoteIdent(ref.table);
    const c = quoteIdent(ref.column);
    const def = column ? defaultSql(ref.table, column) : undefined;
    out.push(`ALTER TABLE ${t} ALTER COLUMN ${c} DROP DEFAULT`);
    out.push(`ALTER TABLE ${t} ALTER COLUMN ${c} TYPE ${name} USING ${c}::text::${name}`);
    if (def !== undefined) out.push(`ALTER TABLE ${t} ALTER COLUMN ${c} SET DEFAULT ${def}`);
  }
  out.push(`DROP TYPE ${old}`);
  return out;
}

/** DDL statements for one migration op. */
export function pgDdl(flavor: PgFlavor, opLike: MigrationOpLike, schema: SchemaIR): string[] {
  const op = opLike as unknown as MigrationOp;
  switch (op.kind) {
    case 'createTable':
      return createTableSql(flavor, op.table);
    case 'dropTable':
      return [`DROP TABLE ${quoteIdent(op.table)}`];
    case 'renameTable': {
      const out = [`ALTER TABLE ${quoteIdent(op.from)} RENAME TO ${quoteIdent(op.to)}`];
      // Keep the primary key constraint name in step with the table name.
      const table = findTable(schema, op.to);
      if (table && table.primaryKey.length > 0 && flavor === 'postgres') {
        out.push(`ALTER TABLE ${quoteIdent(op.to)} RENAME CONSTRAINT ${quoteIdent(`${op.from}_pkey`)} TO ${quoteIdent(`${op.to}_pkey`)}`);
      }
      return out;
    }
    case 'addColumn':
      return [`ALTER TABLE ${quoteIdent(op.table)} ADD COLUMN ${columnDefinition(flavor, op.table, op.column)}`];
    case 'dropColumn':
      return [`ALTER TABLE ${quoteIdent(op.table)} DROP COLUMN ${quoteIdent(op.column)}`];
    case 'renameColumn':
      return [`ALTER TABLE ${quoteIdent(op.table)} RENAME COLUMN ${quoteIdent(op.from)} TO ${quoteIdent(op.to)}`];
    case 'alterColumn':
      return alterColumn(flavor, op);
    case 'createIndex':
      return [createIndexSql(op.table, op.index)];
    case 'dropIndex':
      // CockroachDB drops indexes that back a unique constraint only with CASCADE.
      return [flavor === 'cockroach' ? `DROP INDEX ${quoteIdent(op.table)}@${quoteIdent(op.index.name)} CASCADE` : `DROP INDEX ${quoteIdent(op.index.name)}`];
    case 'addForeignKey':
      return [`ALTER TABLE ${quoteIdent(op.table)} ADD ${foreignKeyClause(op.foreignKey)}`];
    case 'dropForeignKey':
      return [`ALTER TABLE ${quoteIdent(op.table)} DROP CONSTRAINT ${quoteIdent(op.foreignKey.name)}`];
    case 'createEnum':
      return [`CREATE TYPE ${quoteIdent(op.enum.name)} AS ENUM (${op.enum.values.map(quoteString).join(', ')})`];
    case 'dropEnum':
      return [`DROP TYPE ${quoteIdent(op.enum.name)}`];
    case 'alterEnum':
      return alterEnum(flavor, op, schema);
    case 'raw': {
      const sql = typeof op.sql === 'string' ? op.sql : op.sql[flavor];
      return sql ? [sql] : [];
    }
    default:
      throw new TypeError(`Unknown migration op "${(opLike as { kind: string }).kind}"`);
  }
}
