import type { ColumnIR, ForeignKeyIR, IndexIR, MigrationOpLike, SchemaIR, TableIR } from '../../core/ir';
import type { MigrationOp } from '../../migrate/ops';

/** `"name"`, case preserved, with `"` doubled. */
export function quoteIdent(name: string): string {
  return '"' + name.replace(/"/g, '""') + '"';
}

export function quoteString(value: string): string {
  return "'" + value.replace(/'/g, "''") + "'";
}

/**
 * Oracle 12.2 and later accept names up to 128 bytes (30 before). kastor
 * shortens generated constraint names that would not fit, keeping them
 * unique with a short hash.
 */
export const MAX_IDENTIFIER = 128;

export function shortName(name: string, max = MAX_IDENTIFIER): string {
  if (Buffer.byteLength(name, 'utf8') <= max) return name;
  let hash = 0;
  for (const ch of name) hash = (Math.imul(hash, 31) + ch.codePointAt(0)!) >>> 0;
  const suffix = '_' + hash.toString(36);
  let head = name;
  while (Buffer.byteLength(head + suffix, 'utf8') > max) head = head.slice(0, -1);
  return head + suffix;
}

export const checkName = (table: string, column: string) => shortName(`CK_${table}_${column}`);

export function columnType(col: ColumnIR): string {
  if (col.nativeType) return col.nativeType;
  switch (col.type) {
    case 'string':
      return `VARCHAR2(${col.length ?? 255} CHAR)`;
    case 'text':
      return 'CLOB';
    case 'int':
      return 'NUMBER(10)';
    case 'bigint':
      return 'NUMBER(19)';
    case 'float':
      return 'BINARY_DOUBLE';
    case 'decimal':
      return col.precision === undefined ? 'NUMBER' : `NUMBER(${col.precision}, ${col.scale ?? 0})`;
    case 'boolean':
      return 'NUMBER(1)';
    case 'datetime':
      return 'TIMESTAMP(3) WITH TIME ZONE';
    case 'date':
      return 'DATE';
    case 'time':
      return 'INTERVAL DAY(0) TO SECOND(0)';
    case 'json':
      return 'CLOB';
    case 'bytes':
      return 'BLOB';
    case 'uuid':
      return 'CHAR(36 CHAR)';
    case 'enum':
      return `VARCHAR2(${Math.max(1, ...(col.enumValues ?? []).map((v) => v.length))} CHAR)`;
  }
}

export function literal(value: unknown, col: ColumnIR): string {
  if (value === null || value === undefined) return 'NULL';
  if (col.type === 'boolean') return value === true || value === 1 || value === '1' || value === 'true' ? '1' : '0';
  if (col.type === 'json') return quoteString(typeof value === 'string' ? value : JSON.stringify(value));
  if (typeof value === 'number' || typeof value === 'bigint') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (col.type === 'datetime') {
    const date = value instanceof Date ? value : new Date(String(value));
    if (!Number.isNaN(date.getTime())) return `TIMESTAMP '${date.toISOString().replace('T', ' ').replace('Z', '')} +00:00'`;
  }
  if (col.type === 'date') return `DATE '${String(value instanceof Date ? value.toISOString() : value).slice(0, 10)}'`;
  if (col.type === 'time') return `INTERVAL '${String(value)}' HOUR TO SECOND`;
  if (value instanceof Uint8Array) return `HEXTORAW('${Buffer.from(value).toString('hex')}')`;
  return quoteString(String(value));
}

/** A lower case UUID built from SYS_GUID(), usable as a column default. */
export const RANDOM_UUID_SQL =
  "LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID()), '([0-9A-F]{8})([0-9A-F]{4})([0-9A-F]{4})([0-9A-F]{4})([0-9A-F]{12})', '\\1-\\2-\\3-\\4-\\5'))";

export function defaultExpression(col: ColumnIR): string | undefined {
  const def = col.default;
  if (!def || def.kind === 'autoincrement') return undefined;
  switch (def.kind) {
    case 'now':
      if (col.type === 'date') return 'TRUNC(SYS_EXTRACT_UTC(SYSTIMESTAMP))';
      if (col.type === 'time') return "NUMTODSINTERVAL(SYS_EXTRACT_UTC(SYSTIMESTAMP) - CAST(TRUNC(SYS_EXTRACT_UTC(SYSTIMESTAMP)) AS TIMESTAMP), 'DAY')";
      return 'SYSTIMESTAMP';
    case 'random':
      return RANDOM_UUID_SQL;
    case 'sql':
      return String(def.value);
    case 'value':
      return literal(def.value, col);
  }
}

/** The CHECK a column needs: allowed enum values, 0 or 1 for booleans, valid JSON. */
export function checkExpression(col: ColumnIR): string | undefined {
  if (col.nativeType) return undefined;
  const c = quoteIdent(col.name);
  if (col.type === 'enum') return `${c} IN (${(col.enumValues ?? []).map(quoteString).join(', ')})`;
  if (col.type === 'boolean') return `${c} IN (0, 1)`;
  if (col.type === 'json') return `${c} IS JSON`;
  return undefined;
}

export function columnDefinition(table: string, col: ColumnIR): string {
  let sql = `${quoteIdent(col.name)} ${columnType(col)}`;
  if (col.default?.kind === 'autoincrement') sql += ' GENERATED BY DEFAULT ON NULL AS IDENTITY';
  else {
    const def = defaultExpression(col);
    if (def !== undefined) sql += ` DEFAULT ${def}`;
  }
  sql += col.nullable ? ' NULL' : ' NOT NULL';
  const check = checkExpression(col);
  if (check) sql += ` CONSTRAINT ${quoteIdent(checkName(table, col.name))} CHECK (${check})`;
  return sql;
}

const list = (names: string[]) => names.map(quoteIdent).join(', ');

/** Oracle supports ON DELETE CASCADE and SET NULL only; no ON UPDATE actions. */
export function foreignKeyClause(fk: ForeignKeyIR): string {
  let sql = `CONSTRAINT ${quoteIdent(shortName(fk.name))} FOREIGN KEY (${list(fk.columns)}) REFERENCES ${quoteIdent(fk.refTable)} (${list(fk.refColumns)})`;
  if (fk.onDelete === 'cascade') sql += ' ON DELETE CASCADE';
  else if (fk.onDelete === 'set null') sql += ' ON DELETE SET NULL';
  return sql;
}

export function createIndex(table: string, index: IndexIR): string {
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quoteIdent(shortName(index.name))} ON ${quoteIdent(table)} (${list(index.columns)})`;
}

export function createTable(table: TableIR): string[] {
  const lines = table.columns.map((c) => '  ' + columnDefinition(table.name, c));
  if (table.primaryKey.length) lines.push(`  CONSTRAINT ${quoteIdent(shortName(`PK_${table.name}`))} PRIMARY KEY (${list(table.primaryKey)})`);
  for (const fk of table.foreignKeys) lines.push('  ' + foreignKeyClause(fk));
  const statements = [`CREATE TABLE ${quoteIdent(table.name)} (\n${lines.join(',\n')}\n)`];
  for (const index of table.indexes) statements.push(createIndex(table.name, index));
  return statements;
}

/** A PL/SQL block that drops the check constraints on one column, whatever their names. */
export function dropColumnChecks(table: string, column: string): string {
  return [
    'BEGIN',
    '  FOR c IN (SELECT uc.constraint_name FROM user_constraints uc JOIN user_cons_columns cc ON cc.constraint_name = uc.constraint_name AND cc.table_name = uc.table_name',
    `            WHERE uc.table_name = ${quoteString(table)} AND cc.column_name = ${quoteString(column)} AND uc.constraint_type = 'C' AND uc.search_condition_vc NOT LIKE '% IS NOT NULL') LOOP`,
    `    EXECUTE IMMEDIATE 'ALTER TABLE ${quoteIdent(table).replace(/'/g, "''")} DROP CONSTRAINT "' || c.constraint_name || '"';`,
    '  END LOOP;',
    'END;',
  ].join('\n');
}

function alterColumn(op: Extract<MigrationOp, { kind: 'alterColumn' }>): string[] {
  const t = quoteIdent(op.table);
  const c = quoteIdent(op.column);
  const col: ColumnIR = { ...op.to, name: op.column };
  const statements: string[] = [];
  if (op.changes.type) {
    statements.push(dropColumnChecks(op.table, op.column));
    statements.push(`ALTER TABLE ${t} MODIFY (${c} ${columnType(col)})`);
    const check = checkExpression(col);
    if (check) statements.push(`ALTER TABLE ${t} ADD CONSTRAINT ${quoteIdent(checkName(op.table, op.column))} CHECK (${check})`);
  }
  if (op.changes.default) {
    const def = col.default?.kind === 'autoincrement' ? undefined : defaultExpression(col);
    statements.push(`ALTER TABLE ${t} MODIFY (${c} DEFAULT ${def ?? 'NULL'})`);
  }
  if (op.changes.nullable) statements.push(`ALTER TABLE ${t} MODIFY (${c} ${col.nullable ? 'NULL' : 'NOT NULL'})`);
  return statements;
}

/** Migration DDL for Oracle. DDL commits implicitly in Oracle, so a failed migration is not rolled back. */
export function oracleDdl(input: MigrationOpLike, _schema: SchemaIR): string[] {
  const op = input as unknown as MigrationOp;
  const t = (name: string) => quoteIdent(name);
  switch (op.kind) {
    case 'createTable':
      return createTable(op.table);
    case 'dropTable':
      return [`DROP TABLE ${t(op.table)} CASCADE CONSTRAINTS PURGE`];
    case 'renameTable':
      return [`ALTER TABLE ${t(op.from)} RENAME TO ${t(op.to)}`];
    case 'addColumn':
      return [`ALTER TABLE ${t(op.table)} ADD (${columnDefinition(op.table, op.column)})`];
    case 'dropColumn':
      return [`ALTER TABLE ${t(op.table)} DROP COLUMN ${t(op.column)}`];
    case 'renameColumn':
      return [`ALTER TABLE ${t(op.table)} RENAME COLUMN ${t(op.from)} TO ${t(op.to)}`];
    case 'alterColumn':
      return alterColumn(op);
    case 'createIndex':
      return [createIndex(op.table, op.index)];
    case 'dropIndex':
      return [`DROP INDEX ${t(shortName(op.index.name))}`];
    case 'addForeignKey':
      return [`ALTER TABLE ${t(op.table)} ADD ${foreignKeyClause(op.foreignKey)}`];
    case 'dropForeignKey':
      return [`ALTER TABLE ${t(op.table)} DROP CONSTRAINT ${t(shortName(op.foreignKey.name))}`];
    case 'createEnum':
    case 'dropEnum':
    case 'alterEnum':
      return [];
    case 'raw': {
      const sql = typeof op.sql === 'string' ? op.sql : op.sql.oracle;
      return sql ? [sql] : [];
    }
    default:
      throw new Error(`kastor: unknown migration op "${(op as { kind: string }).kind}"`);
  }
}
