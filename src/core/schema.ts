/**
 * The schema DSL: tables, columns, indexes and relations in plain TypeScript.
 * Builders are immutable; every modifier returns a new column. Type
 * information travels in the phantom `_` property so inference needs no
 * generate step.
 */
import type { ColumnDefaultIR, NeutralType, ReferentialAction } from './ir';
import { errors } from './errors';

/* ------------------------------------------------------------------------ */
/* Column type state                                                          */
/* ------------------------------------------------------------------------ */

export interface ColumnState {
  /** TypeScript type of a value (without null). */
  data: unknown;
  /** Neutral database type. */
  type: NeutralType;
  /** `false` after `.nullable()`. */
  notNull: boolean;
  /** Inserts may leave the column out (default, autoincrement, nullable is separate). */
  hasDefault: boolean;
  primaryKey: boolean;
  unique: boolean;
  /** Name of the table this column belongs to, set by `table()`. */
  table: string;
  /** Name of the table a `.references()` points at, `''` when none. */
  references: string;
}

type Mod<S extends ColumnState, P extends Partial<ColumnState>> = {
  [K in keyof ColumnState]: K extends keyof P ? P[K] : S[K];
} & {};

export interface ReferenceOptions {
  onDelete?: ReferentialAction;
  onUpdate?: ReferentialAction;
  /** Constraint name, defaults to `<table>_<columns>_fkey`. */
  name?: string;
}

export interface ColumnConfig {
  type: NeutralType;
  nullable: boolean;
  primaryKey: boolean;
  /** `true` or a custom index name. */
  unique: boolean | string;
  default?: ColumnDefaultIR;
  /** JS side default, called for every insert that leaves the column out. */
  defaultFn?: () => unknown;
  /** Set to the current time by the client on every update. */
  updatedAt?: boolean;
  references?: { target: () => AnyColumn; options: ReferenceOptions };
  /** Database column name when it differs from the property name. */
  dbName?: string;
  length?: number;
  precision?: number;
  scale?: number;
  enumValues?: readonly string[];
  /** Named enum type (Postgres), defaults to `<table>_<column>`. */
  enumName?: string;
  nativeType?: string;
}

const COLUMN = Symbol.for('kastor.column');
const TABLE = Symbol.for('kastor.table');

/** A column of a table. Created through the `t` builders. */
export class Column<S extends ColumnState = ColumnState> {
  /** Phantom type information, never set at runtime. */
  declare readonly _: S;
  readonly [COLUMN] = true;
  readonly config: Readonly<ColumnConfig>;
  /** Property name inside its table, set by `table()`. */
  readonly key: string | undefined;
  /** Database name of its table, set by `table()`. */
  readonly tableName: string | undefined;

  constructor(config: ColumnConfig, key?: string, tableName?: string) {
    this.config = Object.freeze({ ...config });
    this.key = key;
    this.tableName = tableName;
  }

  /** Database column name (`.map()` name or the property name). */
  get name(): string {
    return this.config.dbName ?? this.key ?? '';
  }

  private with<N extends ColumnState>(patch: Partial<ColumnConfig>): Column<N> {
    return new Column<N>({ ...this.config, ...patch }, this.key, this.tableName);
  }

  /** Allows NULL. The select type becomes `T | null` and inserts may leave it out. */
  nullable(): Column<Mod<S, { notNull: false }>> {
    return this.with({ nullable: true });
  }

  /**
   * Default value. A plain value becomes a database default; a function runs
   * in JS for every insert that leaves the column out.
   */
  default(value: S['data'] | (() => S['data'])): Column<Mod<S, { hasDefault: true }>> {
    if (typeof value === 'function') return this.with({ defaultFn: value as () => unknown, default: undefined });
    return this.with({ default: { kind: 'value', value: toJsonDefault(value) }, defaultFn: undefined });
  }

  /** Database default of the current timestamp (datetime, date and time columns). */
  defaultNow(): Column<Mod<S, { hasDefault: true }>> {
    if (!['datetime', 'date', 'time'].includes(this.config.type)) {
      throw errors.schema(
        `defaultNow() needs a datetime, date or time column, got ${this.config.type}.`,
        'Use t.datetime().defaultNow(), or .default(value) for other types.',
      );
    }
    return this.with({ default: { kind: 'now' }, defaultFn: undefined });
  }

  /** Random UUID default (uuid columns). Generated by the database, or by kastor where the database cannot. */
  defaultRandom(): Column<Mod<S, { hasDefault: true }>> {
    if (this.config.type !== 'uuid') {
      throw errors.schema(`defaultRandom() needs a uuid column, got ${this.config.type}.`, 'Use t.uuid().defaultRandom().');
    }
    return this.with({ default: { kind: 'random' }, defaultFn: undefined });
  }

  /** Raw SQL default expression, written into migrations as is. */
  defaultSql(expression: string): Column<Mod<S, { hasDefault: true }>> {
    return this.with({ default: { kind: 'sql', value: expression }, defaultFn: undefined });
  }

  /**
   * Keeps the column at the time of the last write: the client sets it on
   * create (when left out) and on every update, upsert update and updateMany.
   * Datetime, date and time columns.
   */
  updatedAt(): Column<Mod<S, { hasDefault: true }>> {
    if (!['datetime', 'date', 'time'].includes(this.config.type)) {
      throw errors.schema(`updatedAt() needs a datetime, date or time column, got ${this.config.type}.`, 'Use t.datetime().defaultNow().updatedAt().');
    }
    return this.with({ updatedAt: true });
  }

  /** Adds a unique index on this column. */
  unique(name?: string): Column<Mod<S, { unique: true }>> {
    return this.with({ unique: name ?? true });
  }

  /** Marks the column as the primary key. For composite keys use the `primaryKey` table option. */
  primaryKey(): Column<Mod<S, { primaryKey: true; notNull: true }>> {
    return this.with({ primaryKey: true, nullable: false });
  }

  /**
   * Foreign key to another column. Wrap the target in a function so tables
   * can reference each other in any order. For a self reference annotate the
   * return type: `references((): AnyColumn => comments.id)`.
   */
  references<R extends AnyColumn>(target: () => R, options: ReferenceOptions = {}): Column<Mod<S, { references: R['_']['table'] }>> {
    return this.with({ references: { target, options } });
  }

  /** Stores the column under a different database name. */
  map(dbName: string): Column<S> {
    return this.with({ dbName });
  }

  /** Overrides the native database type used by migrations, e.g. `varchar(64)` or `citext`. */
  nativeType(type: string): Column<S> {
    return this.with({ nativeType: type });
  }

  /** Narrows the TypeScript type, e.g. `t.string().$type<'draft' | 'live'>()`. Runtime is unchanged. */
  $type<T>(): Column<Mod<S, { data: T }>> {
    return this.with({});
  }

  /** @internal binds the column to its table. */
  bind(key: string, tableName: string): Column<S> {
    return new Column<S>({ ...this.config }, key, tableName);
  }
}

export type AnyColumn = Column<any>;

export function isColumn(value: unknown): value is AnyColumn {
  return typeof value === 'object' && value !== null && (value as Record<symbol, unknown>)[COLUMN] === true;
}

function toJsonDefault(value: unknown): unknown {
  if (value instanceof Date) return value.toISOString();
  if (typeof value === 'bigint') return value.toString();
  if (value instanceof Uint8Array) return Array.from(value);
  return value;
}

