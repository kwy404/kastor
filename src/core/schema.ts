/* Column builders                                                            */
/* ------------------------------------------------------------------------ */

type Base<T, Ty extends NeutralType, Extra extends Partial<ColumnState> = {}> = Mod<
  { data: T; type: Ty; notNull: true; hasDefault: false; primaryKey: false; unique: false; table: string; references: '' },
  Extra
>;

function col<S extends ColumnState>(type: NeutralType, extra: Partial<ColumnConfig> = {}): Column<S> {
  return new Column<S>({ type, nullable: false, primaryKey: false, unique: false, ...extra });
}

function positiveInt(value: number | undefined, what: string): void {
  if (value !== undefined && (!Number.isInteger(value) || value <= 0)) {
    throw errors.schema(`${what} must be a positive integer, got ${String(value)}.`, `Pass a whole number above zero to ${what}.`);
  }
}

/** Column type builders. Every column is NOT NULL until `.nullable()`. */
export const t = {
  /** Auto increment integer primary key. */
  id: () => col<Base<number, 'int', { hasDefault: true; primaryKey: true }>>('int', { primaryKey: true, default: { kind: 'autoincrement' } }),
  /** Auto increment 64 bit primary key, read as `bigint`. */
  bigId: () => col<Base<bigint, 'bigint', { hasDefault: true; primaryKey: true }>>('bigint', { primaryKey: true, default: { kind: 'autoincrement' } }),
  /** UUID stored natively where possible, read as a string. */
  uuid: () => col<Base<string, 'uuid'>>('uuid'),
  /** Variable length string, `length` defaults to 255 in migrations. */
  string: (length?: number) => {
    positiveInt(length, 't.string(length)');
    return col<Base<string, 'string'>>('string', length === undefined ? {} : { length });
  },
  /** Unbounded text. */
  text: () => col<Base<string, 'text'>>('text'),
  /** 32 bit integer. */
  int: () => col<Base<number, 'int'>>('int'),
  /** 64 bit integer, read as `bigint`. */
  bigint: () => col<Base<bigint, 'bigint'>>('bigint'),
  /** Double precision float. */
  float: () => col<Base<number, 'float'>>('float'),
  /** Exact decimal, read as a string to keep every digit. */
  decimal: (precision = 10, scale = 2) => {
    positiveInt(precision, 't.decimal(precision)');
    if (!Number.isInteger(scale) || scale < 0 || scale > precision) {
      throw errors.schema(`t.decimal scale must be between 0 and the precision (${precision}), got ${scale}.`, 'Use t.decimal(precision, scale) with 0 <= scale <= precision.');
    }
    return col<Base<string, 'decimal'>>('decimal', { precision, scale });
  },
  boolean: () => col<Base<boolean, 'boolean'>>('boolean'),
  /** Timestamp, read as a `Date` (stored in UTC). */
  datetime: () => col<Base<Date, 'datetime'>>('datetime'),
  /** Calendar date, read as `YYYY-MM-DD`. */
  date: () => col<Base<string, 'date'>>('date'),
  /** Time of day, read as `HH:MM:SS`. */
  time: () => col<Base<string, 'time'>>('time'),
  /** JSON document, typed with the generic: `t.json<{ tags: string[] }>()`. */
  json: <T = unknown>() => col<Base<T, 'json'>>('json'),
  /** Binary data, read as `Uint8Array`. */
  bytes: () => col<Base<Uint8Array, 'bytes'>>('bytes'),
  /** One of a fixed list of strings. */
  enum: <const V extends readonly [string, ...string[]]>(values: V, name?: string) => {
    if (!Array.isArray(values) || values.length === 0) {
      throw errors.schema('t.enum needs at least one value.', "Pass the allowed values: t.enum(['user', 'admin']).");
    }
    if (new Set(values).size !== values.length) {
      throw errors.schema(`t.enum values must be unique, got ${values.join(', ')}.`, 'Remove the repeated value.');
    }
    return col<Base<V[number], 'enum'>>('enum', name === undefined ? { enumValues: [...values] } : { enumValues: [...values], enumName: name });
  },
};

