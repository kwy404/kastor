export type ColumnMap = Record<string, AnyColumn>;

export type BindColumns<Name extends string, C extends ColumnMap> = {
  [K in keyof C]: C[K] extends Column<infer S> ? Column<Mod<S, { table: Name }>> : never;
};

export interface TableOptions<C extends ColumnMap = ColumnMap> {
  /** Secondary indexes: `indexes: (p) => [index(p.authorId), uniqueIndex(p.slug, p.siteId)]`. */
  indexes?(columns: C): IndexBuilder[];
  /** Composite primary key: `primaryKey: (p) => [p.postId, p.tagId]`. */
  primaryKey?(columns: C): AnyColumn[];
  /** Foreign keys over several columns: `foreignKeys: (c) => [foreignKey([c.a, c.b], () => [other.x, other.y])]`. */
  foreignKeys?(columns: C): ForeignKeyBuilder[];
  /**
   * Turns deletes into updates that set this nullable datetime column. Reads
   * skip deleted rows unless `withDeleted: true`.
   */
  softDelete?: keyof C & string;
}

export interface TableMeta<Name extends string = string, C extends ColumnMap = ColumnMap> {
  readonly name: Name;
  readonly columns: C;
  readonly options: TableOptions<any>;
}

export type Table<Name extends string = string, C extends ColumnMap = ColumnMap> = {
  readonly [K in keyof C]: C[K];
} & { readonly $table: TableMeta<Name, C> };

export interface AnyTable {
  readonly $table: TableMeta<string, ColumnMap>;
}

const RESERVED_KEYS = new Set(['$table']);
const IDENT = /^[A-Za-z_][A-Za-z0-9_$]*$/;

/**
 * Declares a table.
 *
 * ```ts
 * export const users = table('users', {
 *   id: t.id(),
 *   email: t.string(255).unique(),
 *   name: t.string().nullable(),
 * })
 * ```
 */
export function table<const Name extends string, C extends ColumnMap>(
  name: Name,
  columns: C,
  options: TableOptions<BindColumns<Name, C>> = {},
): Table<Name, BindColumns<Name, C>> {
  if (typeof name !== 'string' || name.length === 0) {
    throw errors.schema('table() needs a name.', "Pass the table name first: table('users', { ... }).");
  }
  if (typeof columns !== 'object' || columns === null || Object.keys(columns).length === 0) {
    throw errors.schema(`Table "${name}" has no columns.`, 'Pass at least one column: table(name, { id: t.id() }).');
  }
  const bound: Record<string, AnyColumn> = {};
  const seen = new Map<string, string>();
  for (const [key, column] of Object.entries(columns)) {
    if (!isColumn(column)) {
      throw errors.schema(`Column "${key}" of table "${name}" is not a column builder.`, 'Build columns with t: { email: t.string() }.');
    }
    if (RESERVED_KEYS.has(key) || !IDENT.test(key)) {
      throw errors.schema(`"${key}" cannot be used as a column name in table "${name}".`, 'Use letters, digits and underscores, and avoid $table. Use .map() for unusual database names.');
    }
    const b = column.bind(key, name);
    const other = seen.get(b.name);
    if (other !== undefined) {
      throw errors.schema(`Columns "${other}" and "${key}" of table "${name}" both map to "${b.name}".`, 'Give each column its own database name.');
    }
    seen.set(b.name, key);
    bound[key] = b;
  }
  if (options.softDelete !== undefined) {
    const c = bound[options.softDelete];
    if (!c) throw errors.schema(`softDelete column "${options.softDelete}" is not a column of "${name}".`, 'Add it: deletedAt: t.datetime().nullable().');
    if (!c.config.nullable || c.config.type !== 'datetime') {
      throw errors.schema(`softDelete column "${options.softDelete}" of "${name}" must be a nullable datetime.`, 'Declare it as t.datetime().nullable().');
    }
  }
  const meta: TableMeta<Name, BindColumns<Name, C>> = Object.freeze({
    name,
    columns: Object.freeze(bound) as BindColumns<Name, C>,
    options: Object.freeze({ ...options }),
  });
  const result: Record<string | symbol, unknown> = { ...bound };
  Object.defineProperty(result, '$table', { value: meta, enumerable: false });
  Object.defineProperty(result, TABLE, { value: true, enumerable: false });
  return Object.freeze(result) as unknown as Table<Name, BindColumns<Name, C>>;
}

export function isTable(value: unknown): value is AnyTable {
  return typeof value === 'object' && value !== null && (value as Record<symbol, unknown>)[TABLE] === true;
}

