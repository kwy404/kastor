import { describe, expect, it } from 'vitest';
import type { ColumnIR, SchemaIR, TableIR } from '../src/core/ir';
import { columnDefinition, columnType, oracleDdl, shortName } from '../src/dialects/oracle/ddl';
import { neutralColumn, parseDefault, parseInCheck } from '../src/dialects/oracle/introspect';

const col = (c: Partial<ColumnIR> & Pick<ColumnIR, 'name' | 'type'>): ColumnIR => ({ nullable: false, ...c });
const empty: SchemaIR = { tables: [] };

describe('oracle ddl', () => {
  it('creates tables with identity columns, checks and constraint names', () => {
    const users: TableIR = {
      name: 'users',
      columns: [
        col({ name: 'id', type: 'int', default: { kind: 'autoincrement' } }),
        col({ name: 'email', type: 'string', length: 120 }),
        col({ name: 'active', type: 'boolean', default: { kind: 'value', value: true } }),
        col({ name: 'role', type: 'enum', enumValues: ['user', "it's"], default: { kind: 'value', value: 'user' } }),
        col({ name: 'meta', type: 'json', nullable: true }),
        col({ name: 'at', type: 'datetime', default: { kind: 'now' } }),
        col({ name: 'token', type: 'uuid', default: { kind: 'random' } }),
      ],
      primaryKey: ['id'],
      indexes: [{ name: 'users_email_key', columns: ['email'], unique: true }],
      foreignKeys: [],
    };
    const [create, index] = oracleDdl({ kind: 'createTable', table: users }, { tables: [users] });
    expect(create).toContain('"id" NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL');
    expect(create).toContain('"email" VARCHAR2(120 CHAR) NOT NULL');
    expect(create).toContain('"active" NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT "CK_users_active" CHECK ("active" IN (0, 1))');
    expect(create).toContain(`"role" VARCHAR2(4 CHAR) DEFAULT 'user' NOT NULL CONSTRAINT "CK_users_role" CHECK ("role" IN ('user', 'it''s'))`);
    expect(create).toContain('"meta" CLOB NULL CONSTRAINT "CK_users_meta" CHECK ("meta" IS JSON)');
    expect(create).toContain('"at" TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL');
    expect(create).toContain('"token" CHAR(36 CHAR) DEFAULT LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID())');
    expect(create).toContain('CONSTRAINT "PK_users" PRIMARY KEY ("id")');
    expect(index).toBe('CREATE UNIQUE INDEX "users_email_key" ON "users" ("email")');
  });

  it('maps every neutral type and literal', () => {
    expect(columnType(col({ name: 'a', type: 'text' }))).toBe('CLOB');
    expect(columnType(col({ name: 'a', type: 'bigint' }))).toBe('NUMBER(19)');
    expect(columnType(col({ name: 'a', type: 'float' }))).toBe('BINARY_DOUBLE');
    expect(columnType(col({ name: 'a', type: 'decimal', precision: 10, scale: 2 }))).toBe('NUMBER(10, 2)');
    expect(columnType(col({ name: 'a', type: 'decimal' }))).toBe('NUMBER');
    expect(columnType(col({ name: 'a', type: 'date' }))).toBe('DATE');
    expect(columnType(col({ name: 'a', type: 'time' }))).toBe('INTERVAL DAY(0) TO SECOND(0)');
    expect(columnType(col({ name: 'a', type: 'bytes' }))).toBe('BLOB');
    expect(columnDefinition('t', col({ name: 'd', type: 'date', default: { kind: 'value', value: '2024-01-02' } }))).toBe(`"d" DATE DEFAULT DATE '2024-01-02' NOT NULL`);
    expect(columnDefinition('t', col({ name: 'w', type: 'datetime', default: { kind: 'value', value: '2024-01-02T03:04:05.678Z' } }))).toBe(
      `"w" TIMESTAMP(3) WITH TIME ZONE DEFAULT TIMESTAMP '2024-01-02 03:04:05.678 +00:00' NOT NULL`,
    );
    expect(columnDefinition('t', col({ name: 'c', type: 'time', nullable: true, default: { kind: 'value', value: '08:30:00' } }))).toBe(
      `"c" INTERVAL DAY(0) TO SECOND(0) DEFAULT INTERVAL '08:30:00' HOUR TO SECOND NULL`,
    );
    expect(columnDefinition('t', col({ name: 'b', type: 'bigint', default: { kind: 'value', value: '9007199254740993' } }))).toBe('"b" NUMBER(19) DEFAULT 9007199254740993 NOT NULL');
  });

  it('shortens names longer than the identifier limit', () => {
    const long = 'x'.repeat(140);
    const short = shortName(long);
    expect(Buffer.byteLength(short)).toBeLessThanOrEqual(128);
    expect(shortName(long)).toBe(short);
    expect(shortName(long + 'y')).not.toBe(short);
    expect(shortName('short')).toBe('short');
    expect(shortName('a_rather_long_constraint_name_for_old_versions', 30)).toHaveLength(30);
  });

  it('alters columns one aspect at a time and keeps only ON DELETE actions', () => {
    const from = col({ name: 'n', type: 'string', length: 10, nullable: true });
    const out = oracleDdl(
      { kind: 'alterColumn', table: 't', column: 'n', from, to: col({ name: 'n', type: 'enum', enumValues: ['a'], default: { kind: 'value', value: 'a' } }), changes: { type: true, nullable: true, default: true } },
      empty,
    );
    expect(out[0]).toContain('BEGIN');
    expect(out[0]).toContain('user_constraints');
    expect(out[1]).toBe('ALTER TABLE "t" MODIFY ("n" VARCHAR2(1 CHAR))');
    expect(out[2]).toBe(`ALTER TABLE "t" ADD CONSTRAINT "CK_t_n" CHECK ("n" IN ('a'))`);
    expect(out[3]).toBe(`ALTER TABLE "t" MODIFY ("n" DEFAULT 'a')`);
    expect(out[4]).toBe('ALTER TABLE "t" MODIFY ("n" NOT NULL)');
    const fk = { name: 'fk', columns: ['a'], refTable: 'p', refColumns: ['id'], onDelete: 'set null' as const, onUpdate: 'cascade' as const };
    expect(oracleDdl({ kind: 'addForeignKey', table: 't', foreignKey: fk }, empty)).toEqual(['ALTER TABLE "t" ADD CONSTRAINT "fk" FOREIGN KEY ("a") REFERENCES "p" ("id") ON DELETE SET NULL']);
    expect(oracleDdl({ kind: 'dropTable', table: 't' }, empty)).toEqual(['DROP TABLE "t" CASCADE CONSTRAINTS PURGE']);
    expect(oracleDdl({ kind: 'renameTable', from: 'a', to: 'b' }, empty)).toEqual(['ALTER TABLE "a" RENAME TO "b"']);
    expect(oracleDdl({ kind: 'dropIndex', table: 't', index: { name: 'i', columns: [], unique: false } }, empty)).toEqual(['DROP INDEX "i"']);
    expect(oracleDdl({ kind: 'raw', sql: { oracle: 'SELECT 1 FROM DUAL' } }, empty)).toEqual(['SELECT 1 FROM DUAL']);
  });
});

describe('oracle introspection helpers', () => {
  it('reads IN checks', () => {
    expect(parseInCheck(`"role" IN ('user', 'it''s')`, 'role')).toEqual(['user', "it's"]);
    expect(parseInCheck('"flag" IN (0, 1)', 'flag')).toEqual(['0', '1']);
    expect(parseInCheck('"other" IN (1)', 'role')).toBeUndefined();
  });

  it('maps catalog types', () => {
    expect(neutralColumn({ DATA_TYPE: 'VARCHAR2', CHAR_LENGTH: 120, CHAR_USED: 'C' })).toEqual({ type: 'string', length: 120 });
    expect(neutralColumn({ DATA_TYPE: 'CHAR', CHAR_LENGTH: 36, CHAR_USED: 'C' })).toEqual({ type: 'uuid' });
    expect(neutralColumn({ DATA_TYPE: 'NUMBER', DATA_PRECISION: 10, DATA_SCALE: 0 })).toEqual({ type: 'int' });
    expect(neutralColumn({ DATA_TYPE: 'NUMBER', DATA_PRECISION: 19, DATA_SCALE: 0 })).toEqual({ type: 'bigint' });
    expect(neutralColumn({ DATA_TYPE: 'NUMBER', DATA_PRECISION: 1, DATA_SCALE: 0 })).toEqual({ type: 'boolean' });
    expect(neutralColumn({ DATA_TYPE: 'NUMBER', DATA_PRECISION: 12, DATA_SCALE: 2 })).toEqual({ type: 'decimal', precision: 12, scale: 2 });
    expect(neutralColumn({ DATA_TYPE: 'TIMESTAMP(3) WITH TIME ZONE' })).toEqual({ type: 'datetime' });
    expect(neutralColumn({ DATA_TYPE: 'TIMESTAMP(6)' })).toEqual({ type: 'datetime', nativeType: 'timestamp(6)' });
    expect(neutralColumn({ DATA_TYPE: 'INTERVAL DAY(0) TO SECOND(0)' })).toEqual({ type: 'time' });
    expect(neutralColumn({ DATA_TYPE: 'BLOB' })).toEqual({ type: 'bytes' });
  });

  it('parses stored defaults', () => {
    expect(parseDefault('SYSTIMESTAMP ', 'datetime')).toEqual({ kind: 'now' });
    expect(parseDefault("LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID()), 'x', 'y'))", 'uuid')).toEqual({ kind: 'random' });
    expect(parseDefault("'it''s'", 'string')).toEqual({ kind: 'value', value: "it's" });
    expect(parseDefault('1', 'boolean')).toEqual({ kind: 'value', value: true });
    expect(parseDefault("TIMESTAMP '2024-01-02 03:04:05.678 +00:00'", 'datetime')).toEqual({ kind: 'value', value: '2024-01-02T03:04:05.678Z' });
    expect(parseDefault("DATE '2024-01-02'", 'date')).toEqual({ kind: 'value', value: '2024-01-02' });
    expect(parseDefault('NULL', 'string')).toBeUndefined();
    expect(parseDefault('1 + 1', 'int')).toEqual({ kind: 'sql', value: '1 + 1' });
  });
});
