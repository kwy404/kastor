import { describe, expect, it } from 'vitest';
import type { ColumnIR, ForeignKeyIR, SchemaIR } from '../src/core/ir';
import { columnType, pgDdl } from '../src/dialects/postgres/ddl';
import { columnFromRow, parseDefault, readStringLiteral, stripCasts } from '../src/dialects/postgres/introspect';
import { applyOp, type MigrationOp } from '../src/migrate/ops';
import { roundTripSchema } from './pg-sqlite-shared';

const users = roundTripSchema.tables.find((tbl) => tbl.name === 'rt_users')!;
const col = (name: string): ColumnIR => users.columns.find((c) => c.name === name)!;
const ddl = (op: MigrationOp, flavor: 'postgres' | 'cockroach' = 'postgres', schema: SchemaIR = roundTripSchema) =>
  pgDdl(flavor, op as never, applyOp(schema, op));

describe('postgres ddl', () => {
  it('creates a table with identity, defaults, enum, keys and indexes', () => {
    const [create, ...indexes] = ddl({ kind: 'createTable', table: users });
    expect(create).toContain('CREATE TABLE "rt_users" (');
    expect(create).toContain('"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(create).toContain(`"role" "rt_users_role" DEFAULT 'user'::"rt_users_role" NOT NULL`);
    expect(create).toContain('"big" bigint DEFAULT 9007199254740993 NOT NULL');
    expect(create).toContain('"balance" numeric(12, 2) DEFAULT 10.50 NOT NULL');
    expect(create).toContain('"createdAt" timestamptz(3) DEFAULT CURRENT_TIMESTAMP NOT NULL');
    expect(create).toContain(`"fixedAt" timestamptz(3) DEFAULT '2024-01-02T03:04:05.678Z' NOT NULL`);
    expect(create).toContain(`"meta" jsonb DEFAULT '{"a":[1,2]}'::jsonb NOT NULL`);
    expect(create).toContain('"token" uuid DEFAULT gen_random_uuid() NOT NULL');
    expect(create).toContain(`"quote" varchar(40) DEFAULT 'O''Brien' NOT NULL`);
    expect(create).toContain('"name" varchar,');
    expect(create).toContain('CONSTRAINT "rt_users_pkey" PRIMARY KEY ("id")');
    expect(indexes).toEqual(['CREATE UNIQUE INDEX "rt_users_email_key" ON "rt_users" ("email")']);
  });

  it('writes foreign keys with their actions', () => {
    const posts = roundTripSchema.tables.find((tbl) => tbl.name === 'rt_posts')!;
    const [create] = ddl({ kind: 'createTable', table: posts });
    expect(create).toContain(
      'CONSTRAINT "rt_posts_author_id_fkey" FOREIGN KEY ("author_id") REFERENCES "rt_users" ("id") ON DELETE CASCADE ON UPDATE CASCADE',
    );
  });

  it('uses int4 on CockroachDB, where INT means INT8', () => {
    expect(columnType('cockroach', 't', { name: 'n', type: 'int', nullable: false })).toBe('int4');
    expect(columnType('postgres', 't', { name: 'n', type: 'int', nullable: false })).toBe('integer');
    expect(columnType('postgres', 't', { name: 'n', type: 'int', nullable: false, nativeType: 'smallint' })).toBe('smallint');
  });

  it('alters type, nullability and defaults', () => {
    const op: MigrationOp = {
      kind: 'alterColumn',
      table: 'rt_users',
      column: 'age',
      from: col('age'),
      to: { ...col('age'), type: 'bigint', nullable: true, default: { kind: 'value', value: '21' } },
      changes: { type: true, nullable: true, default: true },
    };
    expect(ddl(op)).toEqual([
      'ALTER TABLE "rt_users" ALTER COLUMN "age" DROP DEFAULT',
      'ALTER TABLE "rt_users" ALTER COLUMN "age" TYPE bigint USING "age"::bigint',
      'ALTER TABLE "rt_users" ALTER COLUMN "age" SET DEFAULT 21',
      'ALTER TABLE "rt_users" ALTER COLUMN "age" DROP NOT NULL',
    ]);
    expect(ddl(op, 'cockroach')[1]).toBe('SET enable_experimental_alter_column_type_general = true');
  });

  it('switches identity on and off', () => {
    const plain: ColumnIR = { name: 'n', type: 'int', nullable: false };
    const identity: ColumnIR = { ...plain, default: { kind: 'autoincrement' } };
    const schema: SchemaIR = { tables: [{ name: 't', columns: [plain], primaryKey: [], indexes: [], foreignKeys: [] }] };
    const changes = { type: false, nullable: false, default: true };
    expect(ddl({ kind: 'alterColumn', table: 't', column: 'n', from: plain, to: identity, changes }, 'postgres', schema)).toEqual([
      'ALTER TABLE "t" ALTER COLUMN "n" ADD GENERATED BY DEFAULT AS IDENTITY',
    ]);
    expect(ddl({ kind: 'alterColumn', table: 't', column: 'n', from: identity, to: plain, changes }, 'postgres', schema)).toEqual([
      'ALTER TABLE "t" ALTER COLUMN "n" DROP IDENTITY IF EXISTS',
    ]);
  });

  it('adds enum values in place, in the right position', () => {
    const op: MigrationOp = {
      kind: 'alterEnum',
      name: 'rt_users_role',
      from: ['user', 'admin', "it's"],
      to: ['guest', 'user', 'editor', 'admin', "it's", 'owner'],
      added: ['guest', 'editor', 'owner'],
      removed: [],
      columns: [{ table: 'rt_users', column: 'role' }],
    };
    expect(ddl(op)).toEqual([
      `ALTER TYPE "rt_users_role" ADD VALUE 'guest' BEFORE 'user'`,
      `ALTER TYPE "rt_users_role" ADD VALUE 'editor' BEFORE 'admin'`,
      `ALTER TYPE "rt_users_role" ADD VALUE 'owner' AFTER 'it''s'`,
    ]);
  });

  it('recreates the enum type to remove values on Postgres, drops values on CockroachDB', () => {
    const op: MigrationOp = {
      kind: 'alterEnum',
      name: 'rt_users_role',
      from: ['user', 'admin', "it's"],
      to: ['user', 'admin'],
      added: [],
      removed: ["it's"],
      columns: [{ table: 'rt_users', column: 'role' }],
    };
    expect(ddl(op)).toEqual([
      'ALTER TYPE "rt_users_role" RENAME TO "rt_users_role_old"',
      `CREATE TYPE "rt_users_role" AS ENUM ('user', 'admin')`,
      'ALTER TABLE "rt_users" ALTER COLUMN "role" DROP DEFAULT',
      'ALTER TABLE "rt_users" ALTER COLUMN "role" TYPE "rt_users_role" USING "role"::text::"rt_users_role"',
      `ALTER TABLE "rt_users" ALTER COLUMN "role" SET DEFAULT 'user'::"rt_users_role"`,
      'DROP TYPE "rt_users_role_old"',
    ]);
    expect(ddl(op, 'cockroach')).toEqual([`ALTER TYPE "rt_users_role" DROP VALUE 'it''s'`]);
  });

  it('covers the remaining ops', () => {
    const fk: ForeignKeyIR = { name: 'fk', columns: ['a'], refTable: 'rt_users', refColumns: ['id'], onDelete: 'set null', onUpdate: 'no action' };
    const base: SchemaIR = { tables: [{ name: 't', columns: [{ name: 'a', type: 'int', nullable: true }], primaryKey: ['a'], indexes: [], foreignKeys: [] }, users] };
    expect(ddl({ kind: 'dropTable', table: 't' }, 'postgres', base)).toEqual(['DROP TABLE "t"']);
    expect(ddl({ kind: 'renameTable', from: 't', to: 'u' }, 'postgres', base)).toEqual([
      'ALTER TABLE "t" RENAME TO "u"',
      'ALTER TABLE "u" RENAME CONSTRAINT "t_pkey" TO "u_pkey"',
    ]);
    expect(ddl({ kind: 'renameColumn', table: 't', from: 'a', to: 'b' }, 'postgres', base)).toEqual(['ALTER TABLE "t" RENAME COLUMN "a" TO "b"']);
    expect(ddl({ kind: 'dropColumn', table: 't', column: 'a' }, 'postgres', base)).toEqual(['ALTER TABLE "t" DROP COLUMN "a"']);
    expect(ddl({ kind: 'addForeignKey', table: 't', foreignKey: fk }, 'postgres', base)).toEqual([
      'ALTER TABLE "t" ADD CONSTRAINT "fk" FOREIGN KEY ("a") REFERENCES "rt_users" ("id") ON DELETE SET NULL ON UPDATE NO ACTION',
    ]);
    expect(ddl({ kind: 'dropForeignKey', table: 't', foreignKey: fk }, 'postgres', { ...base, tables: [{ ...base.tables[0]!, foreignKeys: [fk] }, users] })).toEqual([
      'ALTER TABLE "t" DROP CONSTRAINT "fk"',
    ]);
    const idx = { name: 'i', columns: ['a'], unique: false };
    expect(ddl({ kind: 'dropIndex', table: 't', index: idx }, 'postgres', base)).toEqual(['DROP INDEX "i"']);
    expect(ddl({ kind: 'dropIndex', table: 't', index: idx }, 'cockroach', base)).toEqual(['DROP INDEX "t"@"i" CASCADE']);
    expect(ddl({ kind: 'createEnum', enum: { name: 'e', values: ['a', 'b'] } }, 'postgres', base)).toEqual([`CREATE TYPE "e" AS ENUM ('a', 'b')`]);
    expect(ddl({ kind: 'dropEnum', enum: { name: 'e', values: ['a'] } }, 'postgres', base)).toEqual(['DROP TYPE "e"']);
    expect(ddl({ kind: 'raw', sql: { postgres: 'SELECT 1', sqlite: 'SELECT 2' } }, 'postgres', base)).toEqual(['SELECT 1']);
    expect(ddl({ kind: 'raw', sql: { sqlite: 'SELECT 2' } }, 'cockroach', base)).toEqual([]);
  });
});

describe('postgres introspection parsing', () => {
  it('reads SQL string literals, escape strings included', () => {
    expect(readStringLiteral("'O''Brien'::text", 0)).toEqual({ value: "O'Brien", end: 10 });
    expect(readStringLiteral("e'x\\'y'", 0)).toEqual({ value: "x'y", end: 7 });
    expect(readStringLiteral('42', 0)).toBeNull();
  });

  it('strips casts and parentheses', () => {
    expect(stripCasts("'abc'::character varying")).toBe("'abc'");
    expect(stripCasts("('now'::text)::date")).toBe("'now'");
    expect(stripCasts("'x':::STRING")).toBe("'x'");
    expect(stripCasts('(-1)')).toBe('-1');
    expect(stripCasts("'a::b'::text")).toBe("'a::b'");
  });

  it('parses defaults from Postgres and CockroachDB catalogs', () => {
    const c = (type: ColumnIR['type']) => ({ type });
    expect(parseDefault("nextval('t_id_seq'::regclass)", c('int'))).toEqual({ kind: 'autoincrement' });
    expect(parseDefault('unique_rowid()', c('bigint'))).toEqual({ kind: 'autoincrement' });
    expect(parseDefault('CURRENT_TIMESTAMP', c('datetime'))).toEqual({ kind: 'now' });
    expect(parseDefault('current_timestamp():::TIMESTAMPTZ', c('datetime'))).toEqual({ kind: 'now' });
    expect(parseDefault('now()', c('datetime'))).toEqual({ kind: 'now' });
    expect(parseDefault("('now'::text)::date", c('date'))).toEqual({ kind: 'now' });
    expect(parseDefault('gen_random_uuid()', c('uuid'))).toEqual({ kind: 'random' });
    expect(parseDefault("'-1'::integer", c('int'))).toEqual({ kind: 'value', value: -1 });
    expect(parseDefault('(-1)', c('int'))).toEqual({ kind: 'value', value: -1 });
    expect(parseDefault("'9007199254740993'::bigint", c('bigint'))).toEqual({ kind: 'value', value: '9007199254740993' });
    expect(parseDefault('1.50', c('decimal'))).toEqual({ kind: 'value', value: '1.50' });
    expect(parseDefault('true', c('boolean'))).toEqual({ kind: 'value', value: true });
    expect(parseDefault(`'{"a": [1, 2]}'::jsonb`, c('json'))).toEqual({ kind: 'value', value: { a: [1, 2] } });
    expect(parseDefault("'\\x01ff'::bytea", c('bytes'))).toEqual({ kind: 'value', value: [1, 255] });
    expect(parseDefault("'2024-01-02 03:04:05.678+00'::timestamp with time zone", c('datetime'))).toEqual({
      kind: 'value',
      value: '2024-01-02T03:04:05.678Z',
    });
    expect(parseDefault("'user'::users_role", c('enum'))).toEqual({ kind: 'value', value: 'user' });
    expect(parseDefault('NULL::character varying', c('string'))).toBeUndefined();
    expect(parseDefault('lower(\'X\')', c('string'))).toEqual({ kind: 'sql', value: "lower('X')" });
    expect(parseDefault(null, c('string'))).toBeUndefined();
  });

  it('maps catalog types to neutral columns', () => {
    const row = (data_type: string, extra: Record<string, unknown> = {}) =>
      columnFromRow(
        {
          table_name: 't',
          column_name: 'c',
          data_type,
          udt_name: String(extra.udt_name ?? ''),
          character_maximum_length: extra.len ?? null,
          numeric_precision: extra.np ?? null,
          numeric_scale: extra.ns ?? null,
          datetime_precision: extra.dp ?? null,
          is_nullable: 'NO',
          column_default: null,
          is_identity: 'NO',
        },
        new Map([['mood', ['ok', 'sad']]]),
      );
    expect(row('character varying', { len: '20' })).toEqual({ name: 'c', type: 'string', nullable: false, length: 20 });
    expect(row('numeric', { np: 10, ns: 2 })).toEqual({ name: 'c', type: 'decimal', nullable: false, precision: 10, scale: 2 });
    expect(row('timestamp with time zone', { dp: 3 })).toEqual({ name: 'c', type: 'datetime', nullable: false });
    expect(row('timestamp with time zone', { dp: 6 })).toMatchObject({ nativeType: 'timestamptz(6)' });
    expect(row('timestamp without time zone', { dp: 6 })).toMatchObject({ type: 'datetime', nativeType: 'timestamp(6)' });
    expect(row('USER-DEFINED', { udt_name: 'mood' })).toEqual({ name: 'c', type: 'enum', nullable: false, enumValues: ['ok', 'sad'], enumName: 'mood' });
    expect(row('USER-DEFINED', { udt_name: 'geometry' })).toMatchObject({ type: 'text', nativeType: 'geometry' });
    expect(row('ARRAY', { udt_name: '_int4' })).toMatchObject({ type: 'text', nativeType: 'int4[]' });
    expect(row('smallint')).toMatchObject({ type: 'int', nativeType: 'smallint' });
    expect(row('json')).toMatchObject({ type: 'json', nativeType: 'json' });
  });
});
